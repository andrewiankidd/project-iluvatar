#!/bin/sh
# The Homepages' app icons (src/manifests/ainur/homepage/pwa.yaml), from
# kiddnet-logo.svg (make-logo.py): the KiddNet logo on the page's #222436, as
# PNGs for the web app manifest and the iPhone's home screen, and the plain AK
# for the browser tab (the globe is fuzz at 32px). Needs rsvg-convert; in a
# throwaway container, from the repository root:
#
#   MSYS_NO_PATHCONV=1 docker run --rm -v "$PWD:/w" -w /w alpine:3.22 \
#     sh -c 'apk add -q rsvg-convert && sh docs/brand/make-icons.sh'
#
# Rewrites pwa.yaml whole; commit it, and Reloader restarts the Homepages.
set -eu
HERE=$(dirname "$0")
REPO=$HERE/../..
LOGO=$HERE/../public/brand/kiddnet-logo.svg
OUT=$REPO/src/manifests/ainur/homepage/pwa.yaml
BG='#222436'
FG='#c0caf5'
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# The logo's own paths, without its <svg> wrapper, to place on a background.
inner=$(sed -e 's/^<svg[^>]*>//' -e 's/<\/svg>$//' "$LOGO")

# icon NAME SIZE SCALE [CONTENT]: CONTENT (default the logo, 200x200) scaled
# to SCALE of the square, centred on the background.
icon() {
  name=$1 size=$2 scale=$3 content=${4:-$inner}
  pad=$(awk "BEGIN { print 100 * (1 - $scale) / $scale }")
  view=$(awk "BEGIN { print 200 + 2 * $pad }")
  printf '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-%s -%s %s %s"><rect x="-%s" y="-%s" width="%s" height="%s" fill="%s"/>%s</svg>' \
    "$pad" "$pad" "$view" "$view" "$pad" "$pad" "$view" "$view" "$BG" "$content" > "$TMP/$name.svg"
  rsvg-convert -w "$size" -h "$size" "$TMP/$name.svg" -o "$TMP/$name.png"
}

# The plain AK (custom.js's mark, without the hover lines), in the logo's colour.
ak="<circle cx=\"100\" cy=\"100\" r=\"90\" fill=\"none\" stroke=\"$FG\" stroke-width=\"8\"/><g stroke=\"$FG\" stroke-width=\"6.4\" stroke-linecap=\"round\"><line x1=\"163.6\" y1=\"36.4\" x2=\"36.4\" y2=\"163.6\"/><line x1=\"36.4\" y1=\"163.6\" x2=\"100\" y2=\"10\"/><line x1=\"100\" y1=\"100\" x2=\"163.6\" y2=\"163.6\"/><line x1=\"100\" y1=\"10\" x2=\"100\" y2=\"190\"/></g>"

icon kiddnet-192 192 0.88
icon kiddnet-512 512 0.88
# Maskable: Android crops it to any shape, keeping only the middle 80%.
icon kiddnet-maskable-512 512 0.74
# The iPhone's home screen (it rounds the corners itself).
icon kiddnet-180 180 0.86
icon kiddnet-favicon-32 32 0.92 "$ak"

{
  cat <<'EOF'
# The Homepages' app icons, so each page installs as an app ("Add to Home
# Screen", or the browser's Install): the KiddNet logo on the page colour.
# Generated by docs/brand/make-icons.sh; don't edit by hand. values.yaml mounts
# it at /app/public/images/kiddnet, which the settings' pwa and favicon name.
apiVersion: v1
kind: ConfigMap
metadata:
  name: homepage-pwa
  annotations:
    # Server-side apply: at ~290 KB it is past the 256 KB limit of the
    # last-applied annotation that client-side apply would add.
    argocd.argoproj.io/sync-options: ServerSideApply=true
binaryData:
EOF
  for f in kiddnet-180 kiddnet-192 kiddnet-512 kiddnet-maskable-512 kiddnet-favicon-32; do
    printf '  %s.png: %s\n' "$f" "$(base64 -w0 "$TMP/$f.png")"
  done
} > "$OUT"
echo "wrote $OUT"
